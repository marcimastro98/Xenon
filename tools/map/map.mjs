// The map of the repo: which feature owns which files, in plain words.
// features.json is the one list a person edits; MAP.md is written from it.
//
//   npm run map             write MAP.md
//   npm run map -- --check  fail when MAP.md is out of date or a file has no owner
//   npm run map -- --unowned  list the files no feature claims

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REPO_ROOT, trackedFiles } from '../quality/repo-files.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const FEATURES_FILE = path.join(HERE, 'features.json');
export const MAP_FILE = path.join(REPO_ROOT, 'MAP.md');
const SHOWN_PATTERNS = 6;

const KEEPING_IT_TRUE = [
  '## Keeping this map true',
  '',
  '- A new file that fits an existing pattern needs nothing.',
  '- A new file that fits none: add its path to the right feature in `tools/map/features.json`, then run `npm run map`.',
  '- A new feature: add an entry (name, one line on what it does, its files), then run `npm run map`.',
  '- `npm test` fails when a file has no owner, a pattern points at nothing, or this page is out of date.',
];

/**
 * `*` stays inside one folder, `**` crosses folders.
 * @param {string} glob
 * @returns {RegExp}
 */
export function globToRegExp(glob) {
  const escaped = glob.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  const body = escaped.replace(/\*\*\/?|\*/g, (star) => (star === '*' ? '[^/]*' : '.*'));
  return new RegExp(`^${body}$`);
}

/**
 * Gives every file to the first feature whose pattern matches it.
 * @param {string[]} files repo-relative paths
 * @param {{id: string, files: string[]}[]} features in order: the first match wins
 * @returns {{ owned: Map<string, string[]>, unowned: string[], unused: string[] }}
 */
export function assign(files, features) {
  const rules = features.flatMap((feature) => feature.files.map((glob) => ({ id: feature.id, glob, test: globToRegExp(glob), hits: 0 })));
  const owned = new Map(features.map((feature) => [feature.id, []]));
  const unowned = [];
  for (const file of files) {
    const rule = rules.find((candidate) => candidate.test.test(file));
    if (!rule) { unowned.push(file); continue; }
    rule.hits += 1;
    owned.get(rule.id).push(file);
  }
  const unused = rules.filter((rule) => rule.hits === 0).map((rule) => `${rule.id}: ${rule.glob}`);
  return { owned, unowned, unused };
}

function whereCell(feature) {
  const shown = feature.files.slice(0, SHOWN_PATTERNS).map((glob) => `\`${glob}\``).join(' ');
  const more = feature.files.length - SHOWN_PATTERNS;
  return more > 0 ? `${shown} and ${more} more` : shown;
}

/**
 * @param {{intro: string[], areas: {id: string, name: string, what: string}[], features: object[]}} map
 * @returns {string} the text of MAP.md. It holds no file counts on purpose: adding a
 *   file to an existing feature must not make the page out of date.
 */
export function render(map) {
  const out = [
    '# Xenon map: who does what',
    '',
    '<!-- Written by `npm run map` from tools/map/features.json. Do not edit this file by hand: -->',
    '<!-- change features.json and run the command. A test fails when the two disagree. -->',
    '',
    ...map.intro,
    '',
  ];
  for (const area of map.areas) {
    const features = map.features.filter((feature) => feature.area === area.id);
    if (features.length === 0) continue;
    out.push(`## ${area.name}`, '', area.what, '', '| Feature | What it does | Where |', '|---|---|---|');
    for (const feature of features) {
      out.push(`| **${feature.name}** | ${feature.what} | ${whereCell(feature)} |`);
    }
    out.push('');
  }
  out.push(...KEEPING_IT_TRUE);
  return `${out.join('\n').trimEnd()}\n`;
}

/** MAP.md is part of the repo even before its first write. */
export function repoFiles(listed) {
  const mapFile = path.relative(REPO_ROOT, MAP_FILE);
  return listed.includes(mapFile) ? listed : [...listed, mapFile].sort();
}

export function readMap() {
  return JSON.parse(readFileSync(FEATURES_FILE, 'utf8'));
}

function main(args) {
  const listed = trackedFiles();
  if (!listed) {
    console.error('No git here: the map needs the list of tracked files.');
    return 1;
  }
  const files = repoFiles(listed);
  const map = readMap();
  const { unowned, unused } = assign(files, map.features);
  if (args.includes('--unowned')) {
    for (const file of unowned) console.log(file);
    console.log(`${unowned.length} files with no owner.`);
    return unowned.length > 0 ? 1 : 0;
  }
  for (const file of unowned) console.log(`no owner: ${file}`);
  for (const rule of unused) console.log(`matches nothing: ${rule}`);
  if (unowned.length > 0 || unused.length > 0) {
    console.log('\nFix tools/map/features.json: every file has one owner, and every pattern matches a file.');
    return 1;
  }
  const text = render(map);
  if (args.includes('--check')) {
    const current = readFileSync(MAP_FILE, 'utf8').replace(/\r\n/g, '\n');
    if (current === text) { console.log('Map: up to date.'); return 0; }
    console.log('MAP.md is out of date. Run: npm run map');
    return 1;
  }
  writeFileSync(MAP_FILE, text);
  console.log(`MAP.md written: ${map.features.length} features, ${files.length} files.`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
